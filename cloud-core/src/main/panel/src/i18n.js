const read = (key) => { try { return localStorage.getItem(key); } catch { return null; } };
const write = (key, value) => { try { localStorage.setItem(key, value); } catch { /* private mode */ } };

export const lang = read('pc-lang') || (navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en');
document.documentElement.lang = lang;

/** Translates an English text; {name} placeholders are filled from vars. */
export function t(text, vars) {
  const s = (lang === 'de' && DE[text]) || text;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k]) : s;
}

export function setLang(value) {
  write('pc-lang', value);
  location.reload(); // shortcut: reload instead of re-rendering every page with the new language
}

// Theme: "light" or "dark", the system setting until the user picks one.
export let theme = read('pc-theme') || (matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark');
document.documentElement.dataset.theme = theme;

export function setTheme(value) {
  theme = value;
  write('pc-theme', value);
  document.documentElement.dataset.theme = value;
}
